import { z } from 'zod';
import { BetaContentBlockSchema } from './content-blocks/index.js';
import { BetaUsageSchema, BetaContainerSchema, BetaStopReasonSchema } from './common/index.js';

/**
 * Beta Message schema matching SDK BetaMessage interface
 * Represents a complete assistant message response from the API
 * @see BetaMessage from \@anthropic-ai/sdk
 */
export const BetaMessageSchema = z.object({
  /**
   * Unique object identifier.
   *
   * The format and length of IDs may change over time.
   */
  id: z.string(),

  /**
   * Object type.
   *
   * For Messages, this is always `"message"`.
   */
  type: z.literal('message'),

  /**
   * Conversational role of the generated message.
   *
   * This will always be `"assistant"`.
   */
  role: z.literal('assistant'),

  /**
   * The model that completed the prompt.
   */
  model: z.string(),

  /**
   * Content generated by the model.
   *
   * This is an array of content blocks, each of which has a `type` that determines
   * its shape.
   */
  content: z.array(BetaContentBlockSchema),

  /**
   * The reason that we stopped.
   *
   * This may be one the following values:
   *
   * - `"end_turn"`: the model reached a natural stopping point
   * - `"max_tokens"`: we exceeded the requested `max_tokens` or the model's maximum
   * - `"stop_sequence"`: one of your provided custom `stop_sequences` was generated
   * - `"tool_use"`: the model invoked one or more tools
   * - `"pause_turn"`: we paused a long-running turn
   * - `"refusal"`: when streaming classifiers intervene to handle potential policy violations
   *
   * In non-streaming mode this value is always non-null. In streaming mode, it is
   * null in the `message_start` event and non-null otherwise.
   */
  stop_reason: BetaStopReasonSchema.nullable().optional(),

  /**
   * Which custom stop sequence was generated, if any.
   *
   * This value will be a non-null string if one of your custom stop sequences was
   * generated.
   */
  stop_sequence: z.string().nullable().optional(),

  /**
   * Billing and rate-limit usage.
   */
  usage: BetaUsageSchema,

  /**
   * Information about the container used in the request (for the code execution tool)
   */
  container: BetaContainerSchema.nullable().optional(),
});

export type BetaMessage = z.infer<typeof BetaMessageSchema>;
