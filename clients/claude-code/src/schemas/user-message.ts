import { z } from 'zod';
import { BaseSdkMessageWithParentToolSchema } from './base.js';
import { MessageParamSchema } from './message-param.js';

/**
 * SDK User Message schema
 * Wraps a MessageParam with SDK metadata (uuid, session_id, parent_tool_use_id)
 * @see SDKUserMessage from \@anthropic-ai/claude-agent-sdk
 */
export const SDKUserMessageSchema = BaseSdkMessageWithParentToolSchema.extend({
  /** Message type discriminator */
  type: z.literal('user'),

  /** The message parameter containing the user content */
  message: MessageParamSchema,

  /**
   * True if this is a 'synthetic' user message which did not originate from
   * the user directly, but instead was generated by the system.
   */
  isSynthetic: z.boolean().optional(),

  /**
   * True if this message is a compaction summary injected after a context reset.
   * Contains the structured summary the LLM sees as continuation context.
   */
  isCompactSummary: z.boolean().optional(),

  /**
   * Tool execution result details (present when message contains tool_result).
   * Provides stdout/stderr and execution metadata from local tool runs.
   */
  tool_use_result: z
    .object({
      stdout: z.string().optional(),
      stderr: z.string().optional(),
      interrupted: z.boolean().optional(),
      isImage: z.boolean().optional(),
    })
    .or(z.string())
    .optional(),
}).refine((message) => !message.isCompactSummary || message.isSynthetic === true, {
  message: 'Compact summary messages must be synthetic',
  path: ['isCompactSummary'],
});

export type SDKUserMessage = z.infer<typeof SDKUserMessageSchema>;
